/**
 * Втягивание области трекинга внутрь сувенира.
 *
 * Зачем. Сувенир держат в руках, и пальцы закрывают именно края. Признаки у
 * края при этом самые сильные: контур высечки — это перепад от фона к рисунку,
 * то есть самый контрастный контур во всём изображении. Трекер на них
 * опирается охотнее всего, поэтому палец на кромке убивает непропорционально
 * много точек, и привязка срывается.
 *
 * Что делаем. В .mind отдаём картинку, у которой внешняя полоса плавно сведена
 * к ровной заливке: детектор там просто не находит признаков, и трекинг
 * вынужден держаться за середину. Размер картинки при этом НЕ меняется —
 * markerDimensions, пропорции и плоскость контента остаются прежними, поэтому
 * ни миграции, ни пересчёта масштаба контента не нужно, а уже собранные .mind
 * продолжают работать как работали.
 *
 * Почему не прямоугольная рамка. Сувениры высечены по контуру, и прямоугольный
 * отступ у фигурной формы срезал бы середину с одной стороны и не тронул край
 * с другой. Поэтому втягиваем сам силуэт: размытая маска прозрачности даёт
 * одновременно и втягивание, и мягкий переход, а для прямоугольного маркера
 * честно вырождается в обычный отступ от краёв.
 */

/**
 * Радиус размытия силуэта.
 *
 * Размытие с сигмой s переводит резкий край в плавный переход: на самом краю
 * значение 0.5, а на глубине примерно 2s внутри — уже почти единица. Нам нужно,
 * чтобы полностью «своей» область становилась на глубине inset, поэтому сигма
 * вдвое меньше требуемого отступа.
 */
export function silhouetteBlurSigma(shortSidePx: number, inset: number): number {
  if (!Number.isFinite(shortSidePx) || shortSidePx <= 0) {
    throw new RangeError('shortSidePx must be a finite positive number');
  }
  if (!Number.isFinite(inset) || inset < 0 || inset >= 0.5) {
    throw new RangeError('inset must be in [0, 0.5)');
  }
  return Math.max(0.5, (shortSidePx * inset) / 2);
}

/** Нижняя граница перехода: на самом краю силуэта размытие даёт ровно 0.5. */
const EDGE = 0.5;
/** Верхняя граница: дальше считаем, что мы уверенно внутри. */
const INSIDE = 0.97;

/**
 * Во сколько взять исходный пиксель: 1 — как есть, 0 — ровная заливка.
 *
 * Переход сглажен намеренно. Резкая граница сама по себе контур, а значит и
 * новые признаки ровно там, где мы их только что убрали.
 */
export function keepWeight(blurred: number): number {
  if (!Number.isFinite(blurred)) return 0;
  if (blurred <= EDGE) return 0;
  if (blurred >= INSIDE) return 1;
  const t = (blurred - EDGE) / (INSIDE - EDGE);
  return t * t * (3 - 2 * t);
}

/**
 * Приближение размытого силуэта на глубине depthPx от края.
 *
 * Нужно только для проверок: позволяет посчитать, какая глубина действительно
 * остаётся нетронутой, не запуская браузерный canvas.
 */
export function blurredEdgeProfile(depthPx: number, sigma: number): number {
  if (!Number.isFinite(sigma) || sigma <= 0) {
    throw new RangeError('sigma must be a finite positive number');
  }
  // Интеграл гауссианы: приближение Аврами-Гастингса для функции ошибок.
  const x = depthPx / (sigma * Math.SQRT2);
  const sign = x < 0 ? -1 : 1;
  const t = 1 / (1 + 0.3275911 * Math.abs(x));
  const erf =
    1 -
    ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t +
      0.254829592) *
      t *
      Math.exp(-x * x);
  return 0.5 * (1 + sign * erf);
}
